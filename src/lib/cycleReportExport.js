/**
 * Turns a succession cycle report into a file an auditor, a board pack or a
 * works council can actually open. The report arrives from the server as flat
 * sections, so the same data becomes one CSV (a block per section, each with
 * its own header row) or the raw JSON.
 */

function cell(value) {
  if (value === null || value === undefined) return "";
  const text = String(value);
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function line(values) {
  return values.map(cell).join(",");
}

export function buildReportCsv(report) {
  if (!report) return "";
  const rows = [];
  const summary = report.summary || {};

  rows.push(line(["Succession cycle report"]));
  rows.push(line(["Cycle", report.cycle?.name]));
  rows.push(line(["Cycle status", report.cycle?.status]));
  rows.push(line(["Stage", report.cycle?.process_stage]));
  rows.push(line(["Generated at", report.generated_at]));
  rows.push(line(["Generated by", report.generated_by_email]));
  rows.push("");

  rows.push(line(["Summary"]));
  rows.push(line(["Measure", "Value"]));
  rows.push(line(["Critical roles", summary.critical_roles]));
  rows.push(line(["Candidates", summary.candidates]));
  rows.push(line(["Ready now", summary.ready_now]));
  rows.push(line(["Ready with conditions", summary.ready_with_conditions]));
  rows.push(line(["Roles covered", summary.roles_covered]));
  rows.push(line(["Roles thin", summary.roles_thin]));
  rows.push(line(["Roles with a gap", summary.roles_gap]));
  rows.push(line(["Decisions ratified", summary.decisions_ratified]));
  rows.push(line(["Decisions awaiting ratification", summary.decisions_awaiting]));
  rows.push(line(["Development actions", summary.development_actions]));
  rows.push(line(["Development actions completed", summary.development_completed]));
  rows.push(line(["Follow-through", summary.follow_through_rate === null ? "n/a" : `${summary.follow_through_rate}%`]));
  rows.push(line(["Transitions active", summary.transitions_active]));
  rows.push(line(["Transitions completed", summary.transitions_completed]));
  rows.push(line(["Active legal holds", summary.active_holds]));
  rows.push(line(["Candidate notices sent", summary.notices_sent]));
  rows.push(line(["Sealed demographic records", summary.sealed_demographics]));

  for (const section of report.sections || []) {
    rows.push("");
    rows.push(line([section.title]));
    if (section.note) rows.push(line([section.note]));
    rows.push(line((section.columns || []).map((column) => column.label)));
    for (const row of section.rows || []) {
      rows.push(line((section.columns || []).map((column) => row[column.key])));
    }
  }

  return rows.join("\n");
}

export function reportFileBaseName(report) {
  const name = report?.cycle?.name || "succession-cycle";
  const stamp = String(report?.generated_at || new Date().toISOString()).slice(0, 10);
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return `${slug || "succession-cycle"}-report-${stamp}`;
}

export function downloadTextFile(filename, mimeType, text) {
  const blob = new Blob([text], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}