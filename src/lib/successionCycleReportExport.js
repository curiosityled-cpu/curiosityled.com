/**
 * Cycle report export. Builds a sectioned CSV from the assembled cycle report —
 * the same numbers the report screen shows, so the file and the screen cannot
 * disagree.
 */

function csvCell(value) {
  if (value === null || value === undefined) return "";
  const text = String(value);
  if (/[",\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
  return text;
}

function section(title, headers, rows) {
  const lines = [[title], headers, ...rows].map((row) => row.map(csvCell).join(","));
  return lines.join("\n");
}

export function buildCycleReportCsv(report) {
  if (!report) return "";
  const { cycle, scope, bench, readiness, evidence, decisions, development, transitions, compliance, audit, rows } = report;

  const parts = [];

  parts.push(section(
    "Cycle",
    ["Cycle", "Status", "Stage", "Start", "End", "Generated at", "Generated by"],
    [[
      cycle.name, cycle.status, cycle.stage, cycle.start_date, cycle.end_date,
      report.generated_at, report.generated_by,
    ]],
  ));

  parts.push(section(
    "Scope",
    ["Candidacies", "Roles in scope", "Evidence records"],
    [[scope.candidacies, scope.roles_in_scope, scope.evidence_records]],
  ));

  parts.push(section(
    "Bench",
    ["Roles", "With a ready successor", "Without a ready successor", "Single-bench roles"],
    [[bench.roles, bench.roles_with_ready, bench.roles_without_ready, bench.single_bench_roles]],
  ));

  parts.push(section(
    "Readiness",
    ["State", "Candidates"],
    Object.entries(readiness || {}).map(([key, value]) => [key, value]),
  ));

  parts.push(section(
    "Evidence",
    ["Total", "Accepted or reviewed", "Draft or submitted"],
    [[evidence.total, evidence.accepted, evidence.draft]],
  ));

  parts.push(section(
    "Decisions",
    ["Total", "Ratified", "Awaiting ratification", "Returned", "Superseded"],
    [[decisions.total, decisions.ratified, decisions.awaiting_ratification, decisions.returned, decisions.superseded]],
  ));

  parts.push(section(
    "Development follow-through",
    ["Actions", "Open", "Overdue", "Due within 14 days", "Completed", "Completed late", "On-time rate %"],
    [[
      development.totals.actions,
      development.closure.open_of_committed,
      development.totals.overdue,
      development.totals.due_soon,
      development.closure.completed,
      development.closure.late,
      development.closure.on_time_rate,
    ]],
  ));

  parts.push(section(
    "Transitions",
    ["Total", "Live", "Completed", "Blocked on knowledge transfer"],
    [[transitions.total, transitions.live, transitions.completed, transitions.blocked]],
  ));

  if (transitions.blocked_detail?.length) {
    parts.push(section(
      "Blocked transitions",
      ["Initiation", "Open knowledge areas"],
      transitions.blocked_detail.map((b) => [b.initiation_id, b.open_areas.join("; ")]),
    ));
  }

  parts.push(section(
    "Compliance",
    ["Active legal holds", "Notices sent", "Notices acknowledged", "Notices in draft", "Sealed demographic rows", "Audit events"],
    [[
      compliance.active_legal_holds, compliance.notices_sent, compliance.notices_acknowledged,
      compliance.notices_draft, compliance.sealed_demographic_rows, audit?.events_recorded,
    ]],
  ));

  parts.push(section(
    "Roles",
    ["Role", "Candidates", "With ready successor", "Decision"],
    (rows?.roles || []).map((r) => [r.role, r.candidates, r.ready, r.decision]),
  ));

  parts.push(section(
    "Candidates",
    ["Candidate", "Status", "Readiness", "Readiness state", "Evidence records"],
    (rows?.candidates || []).map((c) => [c.candidate, c.status, c.readiness, c.readiness_state, c.evidence_count]),
  ));

  return parts.join("\n\n");
}

export function downloadCycleReportCsv(report) {
  const csv = buildCycleReportCsv(report);
  const cycleName = (report?.cycle?.name || "succession-cycle").replace(/[^a-z0-9]+/gi, "-").toLowerCase();
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${cycleName}-cycle-report.csv`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}